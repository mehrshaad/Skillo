/**
 * Builds the one-file Claude Code bridge installers.
 *
 * A Chrome extension cannot write files or touch the registry, so registering a
 * native messaging host will always need something run outside the sandbox.
 * The least we can make that is a single file the user downloads from Settings
 * and double-clicks — so `host.mjs` is embedded here as base64 and these
 * installers carry everything they need.
 *
 * These replaced the old hand-written bridge/install.ps1 and install.sh: one
 * source of truth means the file a store user runs is the same one a developer
 * runs.
 *
 *   node scripts/build-bridge-installers.mjs
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(root, 'public', 'bridge');

const HOST_NAME = 'com.skillo.bridge';

/**
 * Every extension id the host will talk to. The unpacked build is pinned by the
 * `key` in wxt.config.ts; the store build gets its id from Chrome, which is
 * only known after the first upload — fill STORE_EXTENSION_ID in then and
 * regenerate (see docs/findings.md).
 */
const DEV_EXTENSION_ID = 'hfbincjmdcgfhffnpanjdfcccpejdkei';
const STORE_EXTENSION_ID = '';

const hostSource = readFileSync(join(root, 'bridge', 'host.mjs'));
const hostBase64 = hostSource.toString('base64');

const knownIds = [DEV_EXTENSION_ID, STORE_EXTENSION_ID].filter(Boolean);

/* ------------------------------------------------------------------ Windows */

/*
 * The file is a polyglot: line one is batch, which re-runs the rest of the same
 * file through PowerShell. That avoids both batch escaping and the ~32k limit
 * on -EncodedCommand, which the embedded host would otherwise blow past.
 */
// The -replace expression needs its own parentheses: in an argument position
// PowerShell reads the comma as an argument separator and hands Create() two
// arguments instead of one.
const windowsShim =
  '@echo off & setlocal & set "SKILLO_EXT_ID=%~1" & powershell -NoProfile -ExecutionPolicy Bypass -Command "& ([scriptblock]::Create(((Get-Content -LiteralPath \'%~f0\' -Raw) -replace \'(?s)^[^\\r\\n]*\\r?\\n\',\'\')))" & echo. & pause & exit /b';

const windowsScript = `# Skillo bridge installer (generated by scripts/build-bridge-installers.mjs)
$ErrorActionPreference = 'Stop'

$HostName     = '${HOST_NAME}'
$InstallDir   = Join-Path $env:LOCALAPPDATA 'Skillo'
$ManifestPath = Join-Path $InstallDir "$HostName.json"
$LauncherPath = Join-Path $InstallDir 'skillo-bridge.bat'
$HostPath     = Join-Path $InstallDir 'host.mjs'
$RegistryPath = "HKCU:\\Software\\Google\\Chrome\\NativeMessagingHosts\\$HostName"

$Argument = $env:SKILLO_EXT_ID

if ($Argument -eq '--uninstall' -or $Argument -eq '-Uninstall') {
    if (Test-Path $RegistryPath) { Remove-Item -Path $RegistryPath -Recurse -Force }
    if (Test-Path $InstallDir)   { Remove-Item -Path $InstallDir -Recurse -Force }
    Write-Host 'Skillo bridge uninstalled.' -ForegroundColor Green
    exit 0
}

Write-Host 'Installing the Skillo bridge to Claude Code...'
Write-Host ''

$node = Get-Command node -ErrorAction SilentlyContinue
if (-not $node) {
    Write-Host 'Node.js was not found on your PATH.' -ForegroundColor Red
    Write-Host 'Install Node 18 or newer from https://nodejs.org and run this again.'
    exit 1
}
Write-Host "Node:   $($node.Source)"

$claude = Get-Command claude -ErrorAction SilentlyContinue
if ($claude) {
    Write-Host "Claude: $($claude.Source)"
} else {
    Write-Host 'Claude Code was not found on your PATH.' -ForegroundColor Yellow
    Write-Host 'The bridge will install, but Skillo cannot use it until Claude Code is installed.'
}

# Extension ids allowed to talk to this host.
$origins = @(${knownIds.map((id) => `'chrome-extension://${id}/'`).join(', ')})
if ($Argument -and $Argument -notlike '--*') {
    $origins += "chrome-extension://$Argument/"
    Write-Host "Also allowing: $Argument"
}

New-Item -ItemType Directory -Path $InstallDir -Force | Out-Null

# host.mjs travels inside this installer, so there is nothing else to download.
[IO.File]::WriteAllBytes($HostPath, [Convert]::FromBase64String('${hostBase64}'))

# Chrome needs to launch an executable, and .mjs is not one on Windows.
@"
@echo off
"$($node.Source)" "%~dp0host.mjs" %*
"@ | Set-Content -Path $LauncherPath -Encoding ASCII

$manifest = [ordered]@{
    name            = $HostName
    description     = 'Skillo bridge to the local Claude Code CLI'
    path            = $LauncherPath
    type            = 'stdio'
    allowed_origins = $origins
}
$manifest | ConvertTo-Json -Depth 3 | Set-Content -Path $ManifestPath -Encoding UTF8

New-Item -Path $RegistryPath -Force | Out-Null
Set-ItemProperty -Path $RegistryPath -Name '(Default)' -Value $ManifestPath

Write-Host ''
Write-Host 'Skillo bridge installed.' -ForegroundColor Green
Write-Host "Installed to: $InstallDir"
Write-Host ''
Write-Host 'Next: restart Chrome if it was already running, then open Skillo,'
Write-Host 'go to Settings, choose Claude Code, and press Connect.'
`;

/* ------------------------------------------------------------ macOS / Linux */

const posixScript = `#!/usr/bin/env bash
# Skillo bridge installer (generated by scripts/build-bridge-installers.mjs)
set -euo pipefail

HOST_NAME="${HOST_NAME}"
INSTALL_DIR="$HOME/.local/share/skillo"

case "$(uname -s)" in
  Darwin) MANIFEST_DIR="$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts" ;;
  Linux)  MANIFEST_DIR="$HOME/.config/google-chrome/NativeMessagingHosts" ;;
  *) echo "Unsupported platform: $(uname -s). On Windows use skillo-bridge-setup.bat." >&2; exit 1 ;;
esac
MANIFEST_PATH="$MANIFEST_DIR/$HOST_NAME.json"

if [ "\${1:-}" = "--uninstall" ]; then
  rm -f "$MANIFEST_PATH"
  rm -rf "$INSTALL_DIR"
  echo "Skillo bridge uninstalled."
  exit 0
fi

echo "Installing the Skillo bridge to Claude Code..."
echo

command -v node >/dev/null 2>&1 || {
  echo "Node.js was not found on your PATH." >&2
  echo "Install Node 18 or newer from https://nodejs.org and run this again." >&2
  exit 1
}
echo "Node:   $(command -v node)"

if command -v claude >/dev/null 2>&1; then
  echo "Claude: $(command -v claude)"
else
  echo "Claude Code was not found on your PATH." >&2
  echo "The bridge will install, but Skillo cannot use it until Claude Code is installed." >&2
fi

ORIGINS='${knownIds.map((id) => `"chrome-extension://${id}/"`).join(', ')}'
if [ -n "\${1:-}" ]; then
  ORIGINS="$ORIGINS, \\"chrome-extension://\${1}/\\""
  echo "Also allowing: \${1}"
fi

mkdir -p "$INSTALL_DIR" "$MANIFEST_DIR"

# host.mjs travels inside this installer, so there is nothing else to download.
base64 -d > "$INSTALL_DIR/host.mjs" <<'SKILLO_HOST_PAYLOAD'
${hostBase64}
SKILLO_HOST_PAYLOAD
chmod +x "$INSTALL_DIR/host.mjs"

cat > "$MANIFEST_PATH" <<JSON
{
  "name": "$HOST_NAME",
  "description": "Skillo bridge to the local Claude Code CLI",
  "path": "$INSTALL_DIR/host.mjs",
  "type": "stdio",
  "allowed_origins": [$ORIGINS]
}
JSON

echo
echo "Skillo bridge installed."
echo "Installed to: $INSTALL_DIR"
echo
echo "Next: restart Chrome if it was already running, then open Skillo,"
echo "go to Settings, choose Claude Code, and press Connect."
`;

/* --------------------------------------------------------------------- emit */

mkdirSync(OUT_DIR, { recursive: true });

// Batch requires CRLF; the shell script must keep LF.
const windowsFile = `${windowsShim}\n${windowsScript}`.replace(/\r?\n/g, '\r\n');
writeFileSync(join(OUT_DIR, 'skillo-bridge-setup.bat'), windowsFile, 'utf8');
writeFileSync(join(OUT_DIR, 'skillo-bridge-setup.sh'), posixScript.replace(/\r\n/g, '\n'), 'utf8');

console.log(`embedded host.mjs (${hostSource.length} bytes) into:`);
console.log(`  ${join(OUT_DIR, 'skillo-bridge-setup.bat')}`);
console.log(`  ${join(OUT_DIR, 'skillo-bridge-setup.sh')}`);
if (!STORE_EXTENSION_ID) {
  console.log('note: STORE_EXTENSION_ID is still empty — fill it in after the first Web Store upload.');
}
